import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const source=readFileSync('strings-v22.js','utf8');
const cut=(a,b)=>source.slice(source.indexOf(a),source.indexOf(b));
const a={a:{x:.2,y:.3},b:{x:.8,y:.3}},b={a:{x:.1,y:.6},b:{x:.9,y:.6}};
const pointers=new Map(),hands=[{last:null,holding:null},{last:null,holding:null}];
let released=[],redraws=0;
const env={strings:[a,b],pointerStates:pointers,handStates:hands,px:p=>({x:p.x*100,y:p.y*100}),canvas:{hasPointerCapture:()=>true,releasePointerCapture:id=>{assert.equal(pointers.has(id),false);released.push(id);}},redraw:()=>redraws++};
const api=vm.runInNewContext(cut('  function endpointBusy','  function sweep')+cut('  function cancelGestures','  function mode(next)')+'\n;({endpointBusy,nearestEnd,cancelGestures})',env);
pointers.set(1,{type:'move',target:{s:a,side:'a'},before:{...a.a}});
a.a={x:.4,y:.5};
hands[0]={last:{x:1,y:1},holding:{s:b,side:'b',before:{...b.b}}};b.b={x:.6,y:.7};
pointers.set(2,{type:'create',start:{x:.1,y:.1}});
assert.equal(api.endpointBusy(a,'a'),true);assert.equal(api.endpointBusy(b,'b'),true);
assert.equal(api.nearestEnd({x:40,y:50},3),null,'Other input cannot acquire the same endpoint');
api.cancelGestures();
assert.equal(a.a.x,.2);assert.equal(a.a.y,.3);assert.equal(b.b.x,.9);assert.equal(b.b.y,.6);
assert.equal(pointers.size,0);assert.deepEqual(released,[1,2]);assert.equal(hands[0].holding,null);assert.equal(hands[0].last,null);
assert.equal(api.endpointBusy(a,'a'),false);assert.equal(api.nearestEnd({x:20,y:30},3).s,a);
api.cancelGestures();assert.equal(released.length,2);assert.equal(redraws,2);
for(const name of ['mode(next)','setVisible(value)','undoStrings()','demo()'])assert.match(cut('function '+name,'\n  function '+({'mode(next)':'setVisible','setVisible(value)':'drawLine','undoStrings()':'pointerMode','demo()':'finalizeHandTuning'}[name])),/cancelGestures\(\)/);
assert.ok(source.includes("window.addEventListener('blur',cancelGestures)"));assert.ok(source.includes("if(document.hidden)cancelGestures()"));
console.log('PASS cancel restores two endpoints, releases capture, blocks concurrent endpoint ownership, preserves completed strings');
